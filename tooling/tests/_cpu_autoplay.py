"""Shared exact-generated-root cases for both distribution CPU validators."""

import contextlib
import hashlib
import importlib.util
import io
import json
from pathlib import Path
import tempfile


ROOT = Path(__file__).resolve().parents[2]


def check_autoplay_compositions(test, check, cpu, rust_cpu, environment):
    spec = importlib.util.spec_from_file_location(
        "cpu_autoplay_prepare", ROOT / "tooling/rust-autoplay/prepare.py"
    )
    composition = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(composition)
    with tempfile.TemporaryDirectory() as temporary:
        build = Path(temporary).resolve()
        (build / "CMakeCache.txt").write_text("ENABLE_CI_BASELINE_CPU:BOOL=ON\n")
        (build / "compile_commands.json").write_text(
            json.dumps([{"file": "engine.cpp", "arguments": ["clang++", cpu, "-c", "engine.cpp"]}])
        )
        roots = [
            build / "firefly-adapters/rust-origin/lib.rs",
            build / "mite-adapters/rust-nojit/lib.rs",
            build / "firefly-adapters/rust-autoplay/lib.rs",
        ]
        for path, data in zip(roots[:2], [b"// owned origin\n", b"// owned non-JIT\n"]):
            path.parent.mkdir(parents=True)
            path.write_bytes(data)
        # Use the real pinned three-source generator, not an invented autoplay
        # marker: the generated root footer also commits routing and leaf bytes.
        with contextlib.redirect_stdout(io.StringIO()):
            composition.prepare(
                roots[2].parent,
                roots[2].parent / "autoplay-driver",
                str(build / "nojit-driver"),
            )
        prefixes = ["firefly_origin_build_", "mite_nojit_build_", "firefly_autoplay_build_"]
        fingerprints = [hashlib.sha256(path.read_bytes()).hexdigest() for path in roots]
        options = [f"--cfg={prefix}{digest}" for prefix, digest in zip(prefixes, fingerprints)]
        flags = ["-Dwarnings", rust_cpu, *options]
        ninja = build / "build.ninja"

        def command(values):
            ninja.write_text(
                f'COMMAND = cmake -E env "{environment}={" ".join(values)}" cargo build\n'
            )

        def accepted(values):
            command(values)
            with contextlib.redirect_stdout(io.StringIO()):
                check(build)

        def rejected(values):
            command(values)
            with test.assertRaisesRegex(ValueError, "Unexpected generated Cargo"):
                check(build)

        accepted(flags)
        if "LINUX" in environment:
            accepted([*flags[:2], "-Cforce-frame-pointers=yes", *flags[2:]])
        invalid = [
            flags[:-1],  # Missing current autoplay cfg.
            [*flags[:-1], options[-1].replace(fingerprints[-1], "0" * 64)],
            [*flags, options[-1]],
            [*flags, "--cfg=unrelated"],
            [*flags[:2], *reversed(options)],
            [*flags[:2], options[0], options[2], options[1]],
            [flags[0], rust_cpu.replace(rust_cpu.split("=")[-1], "native"), *options],
            flags[1:],  # Keep warnings fatal.
        ]
        for index in range(3):
            invalid.append(
                [*flags[:2], *(option for i, option in enumerate(options) if i != index)]
            )
        for values in invalid:
            rejected(values)
        for path in roots:
            original = path.read_bytes()
            path.write_bytes(original + b"// changed generated bytes\n")
            rejected(flags)
            path.write_bytes(original)
            path.unlink()
            rejected(flags)
            path.write_bytes(original)
        accepted(flags)
        # No autoplay artifact means no autoplay cfg is permitted, even if the
        # retained old command still has a plausible previous SHA256 suffix.
        roots[-1].unlink()
        rejected(flags)
        accepted(flags[:-1])
