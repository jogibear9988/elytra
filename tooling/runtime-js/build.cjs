'use strict';
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const esbuild=require('esbuild');
const root=__dirname;
const destination=path.resolve(root,'../../mite/modules/generated');
const lock=JSON.parse(fs.readFileSync(path.join(root,'package-lock.json'),'utf8'));
const check=process.argv.includes('--check');
const digest=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const external=['node:buffer','node:events','node:process','node:string_decoder'];
const alias={'buffer':'node:buffer','events':'node:events'};
function relative(file){return path.relative(root,file).split(path.sep).join('/');}
function metadata(file){
    let directory=path.dirname(file);
    while(directory!==root && !fs.existsSync(path.join(directory,'package.json'))) directory=path.dirname(directory);
    if(directory===root) return null;
    const pkg=JSON.parse(fs.readFileSync(path.join(directory,'package.json'),'utf8'));
    const pin=lock.packages[relative(directory)];
    if(!pin || pin.version!==pkg.version || !pin.integrity) throw Error(`Unpinned package: ${pkg.name}`);
    const licenses=fs.readdirSync(directory).filter(name=>/^(license|copying)([.-].*)?$/i.test(name)).sort();
    if(!licenses.length) throw Error(`Missing license: ${pkg.name}`);
    const notices=licenses.map(name=>({path:relative(path.join(directory,name)),text:fs.readFileSync(path.join(directory,name),'utf8')}));
    return {name:pkg.name,version:pkg.version,license:pkg.license,integrity:pin.integrity,notices};
}
function save(name,text,manifest){
    const file=path.join(destination,name);
    if(check){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==text)throw Error(`Generated output is stale: ${name}`);}
    else fs.writeFileSync(file,text);
    manifest.files[name]=digest(text);
}
(async()=>{
    const manifest={generator:`esbuild ${esbuild.version}`,builderSha256:digest(fs.readFileSync(__filename)),lockSha256:digest(fs.readFileSync(path.join(root,'package-lock.json'))),files:{},bundles:{}};
    if(!check)fs.mkdirSync(destination,{recursive:true});
    for(const name of ['string-decoder','stream']){
        const result=await esbuild.build({absWorkingDir:root,entryPoints:[`${name}-entry.cjs`],outfile:`${name}.js`,
            bundle:true,format:'cjs',platform:'node',target:'es2022',write:false,metafile:true,
            legalComments:'inline',charset:'utf8',external,alias,logLevel:'silent',
            plugins:[{name:'mite-builtins',setup(build){build.onResolve({filter:new RegExp('^(process|string_decoder)/$')},args=>({path:'node:'+args.path.slice(0,-1),external:true}));}}]});
        if(result.warnings.length)throw Error(JSON.stringify(result.warnings));
        const output=Object.values(result.metafile.outputs)[0];
        const imports=[...new Set(output.imports.map(item=>item.path))].sort();
        if(output.imports.some(item=>!item.external || !external.includes(item.path)))throw Error(`Unexpected import in ${name}`);
        const packages=new Map();
        const sources=Object.keys(result.metafile.inputs).sort().map(input=>{
            const file=path.resolve(root,input);const pkg=metadata(file);if(pkg)packages.set(pkg.name,pkg);
            return {path:input,sha256:digest(fs.readFileSync(file))};
        });
        const records=[...packages.values()].sort((a,b)=>a.name.localeCompare(b.name,'en'));
        const notices=records.map(pkg=>`${pkg.name} ${pkg.version} (${pkg.license})\n`+pkg.notices.map(item=>item.text).join('\n')).join('\n\n');
        if(notices.includes('*/'))throw Error('License requires a safe block-comment representation');
        const source='/* Generated by tooling/runtime-js/build.cjs. Do not edit.\n'+notices+'\n*/\n'+
            '(function (host) {\nconst require=host.require;const module={exports:{}};const exports=module.exports;\n'+
            result.outputFiles[0].text+'\nreturn module.exports;\n})\n';
        save(`${name}.js`,source,manifest);
        save(`${name}.LICENSE.txt`,notices+'\n',manifest);
        manifest.bundles[name]={imports,sources,packages:records.map(({notices,...record})=>({...record,
            notices:notices.map(item=>({path:item.path,sha256:digest(item.text)}))}))};
    }
    const text=JSON.stringify(manifest,null,2)+'\n';
    const file=path.join(destination,'manifest.json');
    if(check){if(fs.readFileSync(file,'utf8')!==text)throw Error('Generated manifest is stale');}
    else fs.writeFileSync(file,text);
    process.stdout.write(check?'Runtime JS bundles reproduce exactly.\n':'Runtime JS bundles generated with pinned inputs and notices.\n');
})().catch(error=>{process.stderr.write(String(error)+'\n');process.exitCode=1;});
